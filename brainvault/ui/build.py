"""Build both Wave | BrainVault front ends from ui/app.js + ui/style.css (no Node needed).

  dashboard/dist/index.js + style.css   -> `hermes dashboard` tab (window.__HERMES_PLUGIN_SDK__, IIFE)
  desktop/plugin.js                     -> Hermes Desktop + Webapp page (@hermes/plugin-sdk, ESM)

Run from brainvault/:  python3 ui/build.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APP = (ROOT / "ui" / "app.js").read_text()
CSS = (ROOT / "ui" / "style.css").read_text()
VERSION = json.loads((ROOT / "dashboard" / "manifest.json").read_text())["version"]
NOTE = "/* GENERATED by ui/build.py from ui/app.js. Do not edit here. Wave | BrainVault %s */\n" % VERSION

DASHBOARD = NOTE + """(function () {
  "use strict";
  var SDK = window.__HERMES_PLUGIN_SDK__;
  if (!SDK || !window.__HERMES_PLUGINS__) return;
  var API = "/api/plugins/brainvault";
  function call(path, body) {
    var init = body === undefined ? undefined : { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) };
    return SDK.fetchJSON(API + path, init).catch(function (e) {
      var m = String((e && e.message) || e), i = m.indexOf("{");
      if (i >= 0) { try { var j = JSON.parse(m.slice(i)); if (j.detail) m = typeof j.detail === "string" ? j.detail : JSON.stringify(j.detail); } catch (_) {} }
      throw new Error(m.replace(/^\\d{3}:\\s*/, ""));
    });
  }
  function open(url) { return !!window.open(url, "_blank", "noopener"); }
""" + APP + """
  window.__HERMES_PLUGINS__.register("brainvault", createWaveBrainVault({ React: SDK.React, call: call, open: open }));
})();
"""

# Desktop / Webapp: map the dashboard's --color-* tokens onto the Desktop's --ui-* theme variables.
DESKTOP_CSS = CSS.replace(
    "--bv-ink:var(--color-foreground,#e8f5f1);--bv-dim:var(--color-muted-foreground,#9db3ad);",
    "--bv-ink:var(--ui-text-primary,var(--color-foreground,#e8f5f1));--bv-dim:var(--ui-text-secondary,var(--color-muted-foreground,#9db3ad));")

DESKTOP = NOTE + """import * as React from 'react'
import { host, ROUTES_AREA, SIDEBAR_NAV_AREA, PALETTE_AREA } from '@hermes/plugin-sdk'

const CSS = """ + json.dumps(DESKTOP_CSS) + """

function errMsg(e) {
  let m = String((e && (e.detail || e.message)) || e)
  const i = m.indexOf('{')
  if (i >= 0) { try { const j = JSON.parse(m.slice(i)); if (j.detail) m = typeof j.detail === 'string' ? j.detail : JSON.stringify(j.detail) } catch (_) {} }
  return m.replace(/^\\d{3}:\\s*/, '')
}

""" + APP + """
export default {
  id: 'brainvault',
  name: 'Wave | BrainVault',
  register(ctx) {
    const style = document.createElement('style')
    style.setAttribute('data-plugin', 'brainvault')
    style.textContent = CSS
    document.head.appendChild(style)
    ctx.onDispose(() => style.remove())

    const call = (path, body) =>
      ctx.rest(path, body === undefined ? {} : { method: 'POST', body }).catch(e => { throw new Error(errMsg(e)) })
    const open = url => { ctx.os.openExternal(url); return true }
    const Page = createWaveBrainVault({ React, call, open })

    ctx.registerMany([
      { id: 'page', area: ROUTES_AREA, data: { path: '/brainvault' }, render: () => React.createElement(Page) },
      { id: 'nav', area: SIDEBAR_NAV_AREA, data: { path: '/brainvault', label: 'Wave | BrainVault', codicon: 'database' } },
      { id: 'open', area: PALETTE_AREA, data: {
        id: 'brainvault.open', label: 'Wave | BrainVault: open memory', keywords: ['wave', 'brainvault', 'memory', 'theta'],
        run: () => host.navigate('/brainvault') } }
    ])
  }
}
"""

(ROOT / "dashboard" / "dist" / "index.js").write_text(DASHBOARD)
(ROOT / "dashboard" / "dist" / "style.css").write_text(CSS)
(ROOT / "desktop").mkdir(exist_ok=True)
(ROOT / "desktop" / "plugin.js").write_text(DESKTOP)
print("built", VERSION, "dashboard", len(DASHBOARD), "desktop", len(DESKTOP))
