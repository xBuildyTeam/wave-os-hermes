"""Build both Wave | Bots front ends from ui/app.js + ui/style.css (no Node needed).

  dashboard/dist/index.js + style.css   -> `hermes dashboard` tab (window.__HERMES_PLUGIN_SDK__, IIFE)
  desktop/plugin.js                     -> Hermes Desktop + Webapp page (@hermes/plugin-sdk, ESM)

Run from wavebots/:  python3 ui/build.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APP = (ROOT / "ui" / "app.js").read_text(encoding="utf-8")
CSS = (ROOT / "ui" / "style.css").read_text(encoding="utf-8")
VERSION = json.loads((ROOT / "dashboard" / "manifest.json").read_text(encoding="utf-8"))["version"]
APP = APP.replace("__WB_UI_VERSION__", VERSION)
NOTE = "/* GENERATED by ui/build.py from ui/app.js. Do not edit here. Wave | Bots %s */\n" % VERSION

DASHBOARD = NOTE + """(function () {
  "use strict";
  var SDK = window.__HERMES_PLUGIN_SDK__;
  if (!SDK || !window.__HERMES_PLUGINS__) return;
  var API = "/api/plugins/wavebots";
  function call(path, body) {
    var init = body === undefined ? undefined : { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) };
    return SDK.fetchJSON(API + path, init).catch(function (e) {
      var m = String((e && e.message) || e), i = m.indexOf("{");
      if (i >= 0) { try { var j = JSON.parse(m.slice(i)); if (j.detail) m = typeof j.detail === "string" ? j.detail : JSON.stringify(j.detail); } catch (_) {} }
      throw new Error(m.replace(/^\\d{3}:\\s*/, ""));
    });
  }
  function open(url) { return !!window.open(url, "_blank", "noopener"); }
  function go(path) { window.location.assign(path); }
""" + APP + """
  window.__HERMES_PLUGINS__.register("wavebots", createWaveBots({ React: SDK.React, call: call, open: open, go: go }));
})();
"""

DESKTOP_CSS = CSS

DESKTOP = NOTE + """import * as React from 'react'
import { host, ROUTES_AREA, SIDEBAR_NAV_AREA, PALETTE_AREA } from '@hermes/plugin-sdk'

const CSS = """ + json.dumps(DESKTOP_CSS) + """

function errMsg(e) {
  let m = String((e && (e.detail || e.message)) || e)
  const i = m.indexOf('{')
  if (i >= 0) { try { const j = JSON.parse(m.slice(i)); if (j.detail) m = typeof j.detail === 'string' ? j.detail : JSON.stringify(j.detail) } catch (_) {} }
  return m.replace(/^\\d{3}:\\s*/, '')
}

""" + APP + """
export default {
  id: 'wavebots',
  name: 'Wave | Bots',
  register(ctx) {
    const style = document.createElement('style')
    style.setAttribute('data-plugin', 'wavebots')
    style.textContent = CSS
    document.head.appendChild(style)
    ctx.onDispose(() => style.remove())

    const call = (path, body) =>
      ctx.rest(path, body === undefined ? {} : { method: 'POST', body }).catch(e => { throw new Error(errMsg(e)) })
    const open = url => { ctx.os.openExternal(url); return true }
    const go = path => host.navigate(path)
    const Page = createWaveBots({ React, call, open, go, desktop: true })

    ctx.registerMany([
      { id: 'page', area: ROUTES_AREA, data: { path: '/wavebots' }, render: () => React.createElement(Page) },
      { id: 'nav', area: SIDEBAR_NAV_AREA, data: { path: '/wavebots', label: 'Wave | Bots', codicon: 'hubot' } },
      { id: 'open', area: PALETTE_AREA, data: {
        id: 'wavebots.open', label: 'Wave | Bots: open the bot store', keywords: ['wave', 'bots', 'theta', 'store'],
        run: () => host.navigate('/wavebots') } }
    ])
  }
}
"""

(ROOT / "dashboard" / "dist" / "index.js").write_text(DASHBOARD, encoding="utf-8")
(ROOT / "dashboard" / "dist" / "style.css").write_text(CSS, encoding="utf-8")
(ROOT / "desktop").mkdir(exist_ok=True)
(ROOT / "desktop" / "plugin.js").write_text(DESKTOP, encoding="utf-8")
print("built", VERSION, "dashboard", len(DASHBOARD), "desktop", len(DESKTOP))
